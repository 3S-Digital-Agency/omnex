export function translate(locale: string, key: string, params?: Params): string {
  const template = messages[locale]?.[key] ?? messages.en[key] ?? key;
  if (!params) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] !== undefined ? String(params[name]) : match,
  );
}

/**
 * Resolve the user's preferred language from their browser on first launch.
 * Accepts an explicit list for testability; otherwise reads navigator.languages.
 */
export function detectBrowserLocale(languages?: readonly string[]): string {
  const candidates = resolveLanguageCandidates(languages);

  for (const candidate of candidates) {
    const primary = candidate.toLowerCase().split('-')[0];
    if (LOCALES.some((option) => option.code === primary)) {
      return primary;
    }
  }

  return 'en';
}

function resolveLanguageCandidates(languages?: readonly string[]): string[] {
  if (languages && languages.length > 0) {
    return [...languages];
  }

  if (typeof navigator === 'undefined') {
    return [];
  }

  if (navigator.languages && navigator.languages.length > 0) {
    return [...navigator.languages];
  }

  return navigator.language ? [navigator.language] : [];
}

export type TranslateFn = (key: string, params?: Params) => string;

export function useI18n(): { locale: string; t: TranslateFn } {
  const { user } = useAuth();
  const locale = user?.locale || detectBrowserLocale();

  return {
    locale,
    t: (key: string, params?: Params) => translate(locale, key, params),
  };
}
